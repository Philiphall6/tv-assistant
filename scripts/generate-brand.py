#!/usr/bin/env python3
"""Generate packaging-only brand assets; never modify the in-launcher HA mark.

Requires fonttools and cairosvg, only when regenerating these committed assets.
Pass a NotoSans-Regular.ttf via --font; no font or external URL is needed at runtime.
"""
import argparse
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
BLUE = "#18BCF2"
WHITE = "#FFFFFF"


def number(value):
    return f"{value:.4f}".rstrip("0").rstrip(".") or "0"


def rect(width, height, radius):
    r, w, h = radius, width, height
    return f"M{r} 0H{w-r}Q{w} 0 {w} {r}V{h-r}Q{w} {h} {w-r} {h}H{r}Q0 {h} 0 {h-r}V{r}Q0 0 {r} 0Z"


def transformed(path, x, y, scale):
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.svgLib.path import parse_path
    pen = SVGPathPen(None, ntos=number)
    parse_path(path, TransformPen(pen, (scale, 0, 0, scale, x, y)))
    return pen.getCommands()


def television(x, y, scale=1):
    paths = [
        {"fill": WHITE, "d": rect(160, 105, 20)},
        {"fill": WHITE, "d": "M26 113H46L40 126H18Q13 126 16 120Z"},
        {"fill": WHITE, "d": "M114 113H134L144 120Q147 126 142 126H120Z"},
        {"fill": "none", "stroke": BLUE, "stroke-width": number(7*scale),
         "d": "M80 22V93M80 85L54 59M80 70L106 44"},
    ]
    for cx, cy in [(80, 22), (54, 59), (106, 44)]:
        paths.append({"fill": BLUE, "d": f"M{cx+8} {cy}A8 8 0 1 1 {cx-8} {cy}A8 8 0 1 1 {cx+8} {cy}Z"})
    return [{**p, "d": transformed(p["d"], x, y, scale)} for p in paths]


def wordmark(font, x, baseline, size=86):
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs, ntos=number)
    for character in "TV Assistant":
        name = cmap[ord(character)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += font["hmtx"].metrics[name][0] * scale
    return {"fill": WHITE, "d": pen.getCommands()}


def svg(width, height, paths):
    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title">',
             '  <title id="title">TV Assistant</title>',
             '  <!-- Generated by scripts/generate-brand.py. Typography is outlined; no external fonts. -->']
    for p in paths:
        attrs = " ".join(f'{k}="{escape(v)}"' for k, v in p.items())
        if "stroke" in p:
            attrs += ' stroke-linecap="round" stroke-linejoin="round"'
        lines.append(f"  <path {attrs}/>")
    return "\n".join([*lines, '</svg>', ''])


def vector(width, height, paths, dp_width, dp_height):
    lines = ['<!-- Generated packaging asset. The in-launcher app_icon.xml remains separate. -->',
             f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{dp_width}dp" android:height="{dp_height}dp" android:viewportWidth="{width}" android:viewportHeight="{height}">']
    for p in paths:
        attrs = {"pathData": p["d"], "fillColor": "#00000000" if p["fill"] == "none" else p["fill"]}
        if "stroke" in p:
            attrs.update(strokeColor=p["stroke"], strokeWidth=p["stroke-width"], strokeLineCap="round", strokeLineJoin="round")
        lines.append('    <path ' + " ".join(f'android:{k}="{escape(v)}"' for k, v in attrs.items()) + '/>')
    return "\n".join([*lines, '</vector>', ''])


def main():
    import cairosvg
    from fontTools.ttLib import TTFont
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    args = parser.parse_args()
    font = TTFont(args.font)
    if font["name"].getDebugName(1) != "Noto Sans" or font["name"].getDebugName(2) != "Regular":
        parser.error("Use Noto Sans Regular to preserve the approved wordmark")
    brand = ROOT / "custom_components/home_assistant_tv/brand"
    drawable = ROOT / "app/src/main/res/drawable"
    icon = [{"fill": BLUE, "d": rect(256, 256, 46)}, *television(40, 58.7, 1.1)]
    logo = [{"fill": BLUE, "d": rect(768, 192, 24)}, *television(28, 33), wordmark(font, 226, 118)]
    banner = [{"fill": BLUE, "d": rect(1200, 675, 30)}, *television(240, 274), wordmark(font, 438, 359)]
    for name, width, height, paths in [("icon", 256, 256, icon), ("logo", 768, 192, logo)]:
        source = svg(width, height, paths)
        (brand / f"{name}.svg").write_text(source)
        for factor, suffix in [(1, ""), (2, "@2x")]:
            cairosvg.svg2png(bytestring=source.encode(), write_to=str(brand / f"{name}{suffix}.png"),
                            output_width=width*factor, output_height=height*factor)
    (brand / "banner.svg").write_text(svg(1200, 675, banner))
    (drawable / "installation_icon.xml").write_text(vector(256, 256, icon, 108, 108))
    (drawable / "tv_banner.xml").write_text(vector(1200, 675, banner, 320, 180))
    print("Generated installation icon, TV banner and HA brand assets; launcher artwork untouched")


if __name__ == "__main__":
    main()
