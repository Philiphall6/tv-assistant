#!/usr/bin/env python3
"""Generate deterministic Android resources and HA UI catalog from reviewed text.

Only localization/en.json is edited by translators. French source labels are
stable keys, never serialized preference names or entity identifiers.
"""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]


def string_id(text):
    value = 0
    raw = text.encode("utf-16-be")
    for index in range(0, len(raw), 2):
        value = (31 * value + int.from_bytes(raw[index:index + 2], "big")) & 0xffffffff
    return "ui_" + format(value, "x")


def outputs():
    catalog = json.loads((ROOT / "localization/en.json").read_text())
    assert all(isinstance(k, str) and isinstance(v, str) and k and v for k, v in catalog.items())
    assert len({string_id(k) for k in catalog}) == len(catalog), "Resource ID collision"
    result = {}
    for language, directory in (("en", "values"), ("fr", "values-fr")):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/generate-localization.py -->', '<resources>']
        for source, english in sorted(catalog.items()):
            value = source if language == "fr" else english
            # Quoting preserves leading/trailing spaces; Android escapes are not XML escapes.
            value = escape(value.replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'").replace('\n', '\\n'))
            lines.append(f'    <string name="{string_id(source)}" formatted="false">"{value}"</string>')
        lines.append('</resources>')
        result[ROOT / f"app/src/main/res/{directory}/ui.xml"] = '\n'.join(lines) + '\n'
    result[ROOT / "custom_components/home_assistant_tv/ui-catalog.js"] = (
        "// Generated by scripts/generate-localization.py; do not edit.\n"
        + "export const EN = " + json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + ";\n"
    )
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.exists() and path.read_text() == content, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Localization resources are current")
